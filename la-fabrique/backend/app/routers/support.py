"""
Support router — bug reporting, ticket management, support chat, and log download.

Endpoints:
- ``POST /v1/support/report_bug``         — submit a new support ticket.
- ``GET  /v1/support/tickets``            — list tickets with optional filters.
- ``GET  /v1/support/tickets/{num}``      — get full detail of a single ticket.
- ``PATCH /v1/support/tickets/{num}``     — update ticket status / resolution,
  and a support admin's decision on severity and category.
- ``GET  /v1/support/agent_record``       — how the Support agent's suggestions
  compared with those decisions.
- ``POST /v1/support/chat``               — bilingual AI support assistant.
- ``GET  /v1/support/logs``               — download structured audit JSONL logs.

Ticket numbers follow the ``FAB-XXXXX`` pattern (zero-padded 5-digit integer)
generated by ``_next_ticket_num()``.

The support chat endpoint is bilingual (English / Spanish) and powered by
Gemini 1.5 Flash via the LLM Proxy.
"""

import os
from datetime import UTC, datetime
from pathlib import Path

from auth_policy import (
    current_user_if_required,
    is_support_admin,
    require_authenticated,
    require_support_admin,
)
from database import get_session
from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import FileResponse
from logging_config import logger
from models import BugReport, User
from schemas import BugReportRequest, BugStatusUpdateRequest, SupportChatRequest
from services.support_agent import CATEGORIES, SEVERITIES, track_record
from sqlmodel import Session, func, select, text

router = APIRouter(prefix="/v1/support", tags=["Support"])

# The statuses in which a ticket is settled: reaching one stamps ``resolved_at``.
TERMINAL_STATUSES = ("resolved", "closed")


def _next_ticket_num(session: Session) -> str:
    """
    Generate the next sequential ticket number in ``FAB-XXXXX`` format.

    Uses ``MAX(id)`` on the ``bug_reports`` table so that ticket numbers are
    monotonically increasing even if rows are deleted.
    """
    result = session.exec(
        text("SELECT COALESCE(MAX(id), 0) + 1 FROM bug_reports")
    ).scalar()
    return f"FAB-{result:05d}"


def _known(value: str | None, allowed: tuple[str, ...], field: str) -> str | None:
    """*value* stripped and lower-cased: None when absent, "" when blank.

    An unknown value is a 400, so the reporter's choice and an admin's
    decision compare as the same words.
    """
    if value is None:
        return None
    choice = value.strip().lower()
    if choice and choice not in allowed:
        raise HTTPException(
            status_code=400, detail=f"Invalid {field}. Use: {', '.join(allowed)}"
        )
    return choice


@router.post("/report_bug")
async def report_bug(req: BugReportRequest, session: Session = Depends(get_session)):  # noqa: B008 - FastAPI dependency marker.
    """
    Create a structured support ticket and return its auto-generated ticket number.

    The caller should store the returned ``ticket_num`` for status polling via
    ``GET /v1/support/tickets/{ticket_num}``.
    """
    # Nothing the reporter did not choose: a default would pass for their claim.
    severity = _known(req.severity, SEVERITIES, "severity") or None
    category = _known(req.category, CATEGORIES, "category") or None
    ticket_num = _next_ticket_num(session)
    report = BugReport(
        ticket_num=ticket_num,
        title=req.title,
        description=req.description,
        steps=req.steps,
        expected=req.expected,
        actual=req.actual,
        severity=severity,
        category=category,
        reporter_email=req.reporter_email,
        browser_info=req.browser_info,
    )
    session.add(report)
    session.commit()
    session.refresh(report)
    logger.info(f"Bug report created: {ticket_num} by {req.reporter_email}")
    return {
        "ticket_num": report.ticket_num,
        "id": report.id,
        "status": report.status,
        "created_at": report.created_at.isoformat(),
        "message": f"Report {report.ticket_num} created. You can track its status at any time.",
    }


def _own_email(user: User | None) -> str | None:
    """The reporter email a non-admin is limited to, or None for admins."""
    if is_support_admin(user):
        return None
    return (user.email or "").lower() if user is not None else ""


@router.get("/tickets")
async def list_tickets(
    reporter_email: str | None = Query(None),
    status: str | None = Query(None),
    severity: str | None = Query(None),
    limit: int = Query(50, le=200),
    session: Session = Depends(get_session),  # noqa: B008 - FastAPI dependency marker.
    user: User | None = Depends(current_user_if_required),  # noqa: B008 - FastAPI dependency marker.
):
    """
    List support tickets with optional filters.

    All filters are additive (AND logic).  ``severity`` matches the impact a
    support admin decided, or the reporter's choice where none was decided.
    Results are ordered by ``created_at`` descending (newest first) and
    capped at *limit* rows.
    Support admins see every ticket; other users only the tickets reported
    with their account email, and asking for another reporter is a 403.
    """
    require_authenticated(user)
    own = _own_email(user)
    if own is not None:
        if reporter_email and reporter_email.strip().lower() != own:
            raise HTTPException(
                status_code=403, detail="You can only see your own tickets"
            )
        reporter_email = own
    query = select(BugReport)
    if reporter_email:
        query = query.where(
            func.lower(BugReport.reporter_email) == reporter_email.lower()
        )
    if status:
        query = query.where(BugReport.status == status)
    if severity:
        # A ticket's impact is what a support admin decided, else what the
        # reporter chose: the filter reads the decision first.
        query = query.where(
            func.lower(func.coalesce(BugReport.decided_severity, BugReport.severity))
            == severity.strip().lower()
        )
    query = query.order_by(BugReport.created_at.desc()).limit(limit)

    rows = session.exec(query).all()
    tickets = [
        {
            "id": r.id,
            "ticket_num": r.ticket_num,
            "title": r.title,
            "severity": r.severity,
            "category": r.category,
            "status": r.status,
            "reporter_email": r.reporter_email,
            "assigned_to": r.assigned_to,
            "suggested_severity": r.suggested_severity,
            "triaged_by": r.triaged_by,
            "decided_severity": r.decided_severity,
            "decided_category": r.decided_category,
            "created_at": r.created_at.isoformat() if r.created_at else None,
            "updated_at": r.updated_at.isoformat() if r.updated_at else None,
            "resolved_at": r.resolved_at.isoformat() if r.resolved_at else None,
        }
        for r in rows
    ]
    return {"tickets": tickets, "count": len(tickets)}


@router.get("/tickets/{ticket_num}")
async def get_ticket(
    ticket_num: str,
    session: Session = Depends(get_session),  # noqa: B008 - FastAPI dependency marker.
    user: User | None = Depends(current_user_if_required),  # noqa: B008 - FastAPI dependency marker.
):
    """
    Return the full detail of a single ticket by its ``FAB-XXXXX`` identifier.

    Ticket numbers are normalised to upper-case before the database lookup.
    A non-admin gets 404 for a ticket someone else reported.
    """
    require_authenticated(user)
    report = session.exec(
        select(BugReport).where(BugReport.ticket_num == ticket_num.upper())
    ).first()
    own = _own_email(user)
    if report and own is not None and (report.reporter_email or "").lower() != own:
        report = None
    if not report:
        raise HTTPException(status_code=404, detail=f"Ticket {ticket_num} not found")
    return {
        "id": report.id,
        "ticket_num": report.ticket_num,
        "title": report.title,
        "description": report.description,
        "steps": report.steps,
        "expected": report.expected,
        "actual": report.actual,
        "severity": report.severity,
        "category": report.category,
        "status": report.status,
        "reporter_email": report.reporter_email,
        "assigned_to": report.assigned_to,
        "resolution": report.resolution,
        # The Support agent's triage: suggestions, beside the reporter's choice.
        "agent_reply": report.agent_reply,
        "suggested_severity": report.suggested_severity,
        "suggested_category": report.suggested_category,
        "triaged_by": report.triaged_by,
        "triaged_at": report.triaged_at.isoformat() if report.triaged_at else None,
        # A support admin's decision, apart from the reporter's and the agent's.
        "decided_severity": report.decided_severity,
        "decided_category": report.decided_category,
        "decided_by": report.decided_by,
        "decided_at": report.decided_at.isoformat() if report.decided_at else None,
        "browser_info": report.browser_info,
        "created_at": report.created_at.isoformat() if report.created_at else None,
        "updated_at": report.updated_at.isoformat() if report.updated_at else None,
        "resolved_at": report.resolved_at.isoformat() if report.resolved_at else None,
    }


@router.patch("/tickets/{ticket_num}")
async def update_ticket_status(
    ticket_num: str,
    req: BugStatusUpdateRequest,
    session: Session = Depends(get_session),  # noqa: B008 - FastAPI dependency marker.
    user: User | None = Depends(current_user_if_required),  # noqa: B008 - FastAPI dependency marker.
):
    """
    Update the status (and optionally resolution / assignee) of a ticket.

    When the status reaches ``"resolved"`` or ``"closed"``, ``resolved_at``
    is set to the current UTC timestamp; a later save keeps it, and
    reopening the ticket clears it.
    A ``severity`` or ``category`` is the admin's decision: it is stored apart
    from the reporter's choice and the Support agent's suggestion. Omitted, the
    earlier decision stays; an empty string clears it.
    Requires a support admin.
    """
    require_support_admin(user)
    valid_statuses = {"open", "in_progress", "waiting", "resolved", "closed"}
    if req.status not in valid_statuses:
        raise HTTPException(
            status_code=400, detail=f"Invalid status. Use: {valid_statuses}"
        )
    decisions = {
        "severity": _known(req.severity, SEVERITIES, "severity"),
        "category": _known(req.category, CATEGORIES, "category"),
    }

    report = session.exec(
        select(BugReport).where(BugReport.ticket_num == ticket_num.upper())
    ).first()
    if not report:
        raise HTTPException(status_code=404, detail=f"Ticket {ticket_num} not found")

    was_terminal = report.status in TERMINAL_STATUSES
    report.status = req.status
    if req.resolution:
        report.resolution = req.resolution
    if req.assigned_to:
        report.assigned_to = req.assigned_to
    report.updated_at = datetime.now(UTC).replace(tzinfo=None)
    # Stamped only when a decision changes: saving a ticket's status does not
    # credit whoever saved it with an earlier decision.
    changed = False
    for field, value in decisions.items():
        if value is not None and getattr(report, f"decided_{field}") != (value or None):
            setattr(report, f"decided_{field}", value or None)
            changed = True
    if changed:
        decided = bool(report.decided_severity or report.decided_category)
        who = user.email if user is not None else "support admin"
        report.decided_by = who if decided else None
        report.decided_at = report.updated_at if decided else None
    # ``resolved_at`` is when the ticket reached a terminal state: a later save
    # of a resolved ticket (a decision, say) keeps it, and reopening clears it.
    if req.status not in TERMINAL_STATUSES:
        report.resolved_at = None
    elif not was_terminal:
        report.resolved_at = datetime.now(UTC).replace(tzinfo=None)

    session.add(report)
    session.commit()
    session.refresh(report)
    return {
        "ticket_num": report.ticket_num,
        "status": report.status,
        "updated_at": report.updated_at.isoformat(),
        "decided_severity": report.decided_severity,
        "decided_category": report.decided_category,
        "decided_by": report.decided_by,
    }


@router.get("/agent_record")
async def support_agent_record(
    session: Session = Depends(get_session),  # noqa: B008 - FastAPI dependency marker.
    user: User | None = Depends(current_user_if_required),  # noqa: B008 - FastAPI dependency marker.
):
    """How the Support agent's suggestions compared with support admins' decisions.

    Per field (``severity``, ``category``), over the tickets the agent triaged
    and an admin decided: how many, how many the agent matched and how many it
    gave no usable answer for, how many reporters chose a value and how many of
    those matched. Counted from the tickets; requires a support admin.
    """
    require_support_admin(user)
    return track_record(session)


@router.post("/chat")
async def support_chat(req: SupportChatRequest):
    """
    Bilingual AI support assistant powered by Gemini 1.5 Flash.

    Prepends a fixed system prompt that instructs the model to answer in the
    same language the user is writing in (English or Spanish).  The entire
    conversation history is forwarded on each request so the model has context
    from previous turns.

    Raises HTTP 503 if the LLM Proxy is unavailable.
    """
    import httpx

    # System prompt — defines the assistant's role and bilingual behaviour.
    system_prompt = {
        "role": "system",
        "content": (
            "You are the Fabrique Enterprise Support Bot. "
            "You help users manage their autonomous AI engineering teams. "
            "Explain concepts like 'Sprints', 'Autonomy Levels', 'Engrams', and 'Glassroom' simply. "
            "If they report a bug, tell them to use the 'Bug Reporter' tab (the red bug icon). "
            "Keep answers concise, professional, and friendly. "
            "CRITICAL: You are fully bilingual. You MUST reply in the same language the user uses (English or Spanish)."
        ),
    }
    formatted_messages = [system_prompt] + [msg.model_dump() for msg in req.messages]
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            r = await client.post(
                f"{os.getenv('LLM_PROXY_URL', 'http://llm-proxy:5100')}/v1/chat/completions",
                json={
                    "model": "gemini-1.5-flash",
                    "messages": formatted_messages,
                    "max_tokens": 512,
                    "temperature": 0.7,
                },
            )
            r.raise_for_status()
            reply = r.json()["choices"][0]["message"]["content"]
            return {"reply": reply}
    except Exception as e:  # noqa: BLE001 - Translate upstream chat failures to a sanitized API error.
        logger.warning(f"Support chat LLM error: {e}")
        raise HTTPException(status_code=503, detail="LLM service unavailable")


@router.get("/logs")
async def download_support_logs(
    user: User | None = Depends(current_user_if_required),  # noqa: B008 - FastAPI dependency marker.
):
    """
    Download the latest structured audit log as a JSONL file (support admins).

    Returns the file at ``AUDIT_LOG_PATH/audit.jsonl`` as an attachment.
    Raises HTTP 404 if no log file exists yet (e.g. no workflow has run).
    """
    require_support_admin(user)
    log_path = Path(os.getenv("AUDIT_LOG_PATH", "/app/.factory/logs")) / "audit.jsonl"
    if log_path.exists():
        return FileResponse(
            path=log_path,
            filename=f"fabrique_support_logs_{datetime.now(UTC).strftime('%Y%m%d')}.jsonl",
        )
    raise HTTPException(status_code=404, detail="Log file not found.")
